#!/usr/bin/env python3
"""Generate VEXA design tokens for Compose, web dashboards and VEXA MAP.

Run from any directory: python tools/sync_design_tokens.py
No dependencies, no network access. Source of truth: design/tokens.json.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
THEME = json.loads((ROOT / 'design/tokens.json').read_text(encoding='utf-8'))
C = THEME['colors']

def kotlin_color(hex_value: str) -> str:
    return f'Color(0xFF{hex_value.lstrip("#").upper()})'

def theme_kotlin(package: str) -> str:
    colors = {
        'graphite': 'graphite950',
        'surfaceDark': 'graphite900',
        'surfaceElevated': 'graphite800',
        'mutedTeal': 'primary',
        'brightRoute': 'navigation',
        'lightCanvas': 'canvas',
        'lightSurface': 'surface',
        'textDark': 'textPrimary',
        'textLight': 'textOnLight',
    }
    props = '\n'.join(f'    val {attr} = {kotlin_color(C[token])}' for attr, token in colors.items())
    return f'''// Auto-generated by tools/sync_design_tokens.py. Do not edit this file directly.
package {package}

import androidx.compose.material3.ColorScheme
import androidx.compose.material3.darkColorScheme
import androidx.compose.material3.lightColorScheme
import androidx.compose.ui.graphics.Color

/** Shared VEXA graphite + calm turquoise; navigation line uses brightRoute only. */
internal object VexaDesign {{
{props}

    fun darkScheme(): ColorScheme = darkColorScheme(
        primary = mutedTeal,
        onPrimary = {kotlin_color(C['onPrimary'])},
        primaryContainer = {kotlin_color(C['graphite800'])},
        onPrimaryContainer = textDark,
        secondary = mutedTeal,
        onSecondary = {kotlin_color(C['onPrimary'])},
        background = graphite,
        onBackground = textDark,
        surface = surfaceDark,
        onSurface = textDark,
        surfaceVariant = surfaceElevated,
        onSurfaceVariant = {kotlin_color(C['textSecondary'])},
        outline = {kotlin_color(C['borderDark'])},
        error = {kotlin_color(C['danger'])}
    )

    fun lightScheme(): ColorScheme = lightColorScheme(
        primary = {kotlin_color(C['lightPrimary'])},
        onPrimary = {kotlin_color(C['onPrimaryLight'])},
        primaryContainer = {kotlin_color(C['lightPrimarySoft'])},
        onPrimaryContainer = textLight,
        secondary = {kotlin_color(C['lightPrimary'])},
        onSecondary = {kotlin_color(C['onPrimaryLight'])},
        background = lightCanvas,
        onBackground = textLight,
        surface = lightSurface,
        onSurface = textLight,
        surfaceVariant = {kotlin_color(C['lightSurfaceAlt'])},
        onSurfaceVariant = {kotlin_color(C['lightTextSecondary'])},
        outline = {kotlin_color(C['borderLight'])},
        error = {kotlin_color(C['lightDanger'])}
    )
}}
'''

def web_css():
    return f'''/* Generated by tools/sync_design_tokens.py, VEXA design {THEME['version']} */
:root {{
  color-scheme: dark;
  --vexa-graphite: {C['graphite950']};
  --vexa-surface: {C['graphite900']};
  --vexa-surface-2: {C['graphite800']};
  --vexa-canvas: {C['graphite950']};
  --vexa-primary: {C['primary']};
  --vexa-primary-hover: {C['primaryHover']};
  --vexa-primary-soft: {C['primarySoft']};
  --vexa-route: {C['navigation']};
  --vexa-ink: {C['graphite950']};
  --vexa-navy: {C['graphite900']};
  --vexa-text: {C['textPrimary']};
  --vexa-text-secondary: {C['textSecondary']};
  --vexa-on-primary: {C['onPrimary']};
  --vexa-border: {C['borderDark']};
  --vexa-success: {C['success']};
  --vexa-warning: {C['warning']};
  --vexa-danger: {C['danger']};
  --vexa-card-radius: {THEME['radii']['card']}px;
}}
'''

for platform in ('client', 'driver'):
    package = f'ru.vexa.{platform}'
    f = ROOT / f'android/{platform}/app/src/main/java/ru/vexa/{platform}/VexaDesign.kt'
    f.write_text(theme_kotlin(package), encoding='utf-8')
(ROOT / 'dispatcher/src/brand.css').write_text(web_css(), encoding='utf-8')
(ROOT / 'platform-admin/src/vexa-brand.css').write_text(web_css(), encoding='utf-8')
# Keep style.json and Android navigation in sync at source level.
map_palette = ROOT / 'VEXA_MAP/design-palette.json'
map_palette.write_text(json.dumps({'version': THEME['version'], 'background': C['graphite950'],
    'navigationRoute': C['navigation'], 'marker': C['primary'], 'foreground': C['textPrimary']},
    ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
print('VEXA theme generated for Client, Driver, Dispatcher, Admin, MAP')
