BEGIN;

-- ------------------------------------------------------------
-- DISPATCHERS
-- ------------------------------------------------------------

CREATE TABLE dispatchers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    username VARCHAR(80) NOT NULL UNIQUE,

    password_hash VARCHAR(255) NOT NULL,

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    role VARCHAR(30) NOT NULL DEFAULT 'dispatcher',

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX dispatchers_username_idx
    ON dispatchers(username);


-- ------------------------------------------------------------
-- ORDERS
-- ------------------------------------------------------------

CREATE TABLE orders (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    city_id VARCHAR(80) NOT NULL DEFAULT 'obolensk',

    customer_name VARCHAR(120),

    customer_phone VARCHAR(40) NOT NULL,

    anonymous BOOLEAN NOT NULL DEFAULT FALSE,

    pickup_address VARCHAR(500) NOT NULL,

    destination_address VARCHAR(500) NOT NULL,

    pickup_latitude DOUBLE PRECISION,

    pickup_longitude DOUBLE PRECISION,

    destination_latitude DOUBLE PRECISION,

    destination_longitude DOUBLE PRECISION,

    status VARCHAR(40) NOT NULL DEFAULT 'new',

    payment_method VARCHAR(30) NOT NULL DEFAULT 'cash',

    price_rub INTEGER,

    driver_id INTEGER,

    comment TEXT,

    idempotency_key VARCHAR(128) NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_orders_city_idempotency
        UNIQUE (city_id, idempotency_key),

    CONSTRAINT orders_price_nonnegative
        CHECK (price_rub IS NULL OR price_rub >= 0),

    CONSTRAINT orders_payment_method_check
        CHECK (
            payment_method IN (
                'cash',
                'driver_transfer',
                'card',
                'sbp'
            )
        ),

    CONSTRAINT orders_pickup_latitude_check
        CHECK (
            pickup_latitude IS NULL
            OR pickup_latitude BETWEEN -90 AND 90
        ),

    CONSTRAINT orders_pickup_longitude_check
        CHECK (
            pickup_longitude IS NULL
            OR pickup_longitude BETWEEN -180 AND 180
        ),

    CONSTRAINT orders_destination_latitude_check
        CHECK (
            destination_latitude IS NULL
            OR destination_latitude BETWEEN -90 AND 90
        ),

    CONSTRAINT orders_destination_longitude_check
        CHECK (
            destination_longitude IS NULL
            OR destination_longitude BETWEEN -180 AND 180
        )
);


-- ------------------------------------------------------------
-- INDEXES
-- ------------------------------------------------------------

CREATE INDEX orders_city_status_idx
    ON orders(city_id, status, created_at DESC);

CREATE INDEX orders_driver_idx
    ON orders(driver_id);

CREATE INDEX orders_phone_idx
    ON orders(customer_phone);

CREATE INDEX orders_created_at_idx
    ON orders(created_at DESC);


COMMIT;
